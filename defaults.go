// Package golm хранит ресурсы, общие для CLI и GUI.
//
// [GUI-без-файла] Файл добавлен, чтобы оконная версия работала без config.yaml.
// Директива //go:embed видит только файлы своей папки и вложенных папок,
// поэтому встраивание config.example.yaml возможно только из корня модуля:
// из gui/ или internal/config до него не дотянуться.
//
// CLI этот пакет не использует: он, как и раньше, читает config.yaml из текущей папки.
package golm

import _ "embed"

// DefaultConfigYAML — содержимое config.example.yaml, встроенное в программу при сборке.
// GUI берет из него значения по умолчанию, пока пользователь не сохранил свои настройки,
// и использует его как основу для нового файла настроек (вместе с комментариями).
//
//go:embed config.example.yaml
